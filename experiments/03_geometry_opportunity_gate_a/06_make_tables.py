SCRIPTS_DIR = Path(__file__).resolve().parent
if str(SCRIPTS_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPTS_DIR))

from common import load_json, write_csv

ROOT = Path(__file__).resolve().parents[2] if Path(__file__).resolve().parents[1].name == "experiments" else Path(__file__).resolve().parents[1]


def format_val(v, prec=4):
    if v is None:
        return "---"
    if isinstance(v, (int,)):
        return str(v)
    if isinstance(v, (float,)):
        return f"{v:.{prec}f}"
    return str(v)


def format_ci(ci, prec=4):
    if not ci or ci[0] is None or ci[1] is None:
        return "---"
    return f"[{ci[0]:.{prec}f}, {ci[1]:.{prec}f}]"


def make_tables(e6_summary_path: str | Path, heldout_summary_path: str | Path | None, out_dir: str | Path):
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    
    s_can = load_json(e6_summary_path)
    s_held = load_json(heldout_summary_path) if (heldout_summary_path and Path(heldout_summary_path).exists()) else None

    # Defensive getters for canonical summary
    can_ora = s_can.get("observed_oracle_opportunity", {})
    can_on = s_can.get("observed_online_gain", {})
    can_cap = s_can.get("oracle_gain_capture", {})
    can_corr = s_can.get("correlation", {})
    can_reg = s_can.get("regression", {})

    # Defensive getters for heldout summary
    held_ora = s_held.get("oracle_opportunity", {}) if s_held else {}
    held_on = s_held.get("online_gain", {}) if s_held else {}
    held_cap = s_held.get("capture", {}) if s_held else {}

    metrics = [
        ("Evaluated Cases", s_can.get("n_online_valid", s_can.get("n_cases_total")), s_held.get("n_cases_valid") if s_held else "---"),
        ("Median Oracle Headroom $\\Delta_{\\rm oracle}^{\\rm obs}$", 
         f"{format_val(can_ora.get('median'))}",
         f"{format_val(held_ora.get('median'))}" if s_held else "---"),
        ("Median Online Gain $\\Delta_{\\rm online}^{\\rm obs}$", 
         f"{format_val(can_on.get('median'))}",
         f"{format_val(held_on.get('median'))}" if s_held else "---"),
        ("Median Capture Ratio $R_{\\rm capture}$", 
         f"{format_val(can_cap.get('median'))} {format_ci(can_cap.get('bootstrap95_median'))}",
         f"{format_val(held_cap.get('median'))}" if s_held else "---"),
        ("Capture $\\ge 0.50$ (Fraction)", 
         f"{format_val(can_cap.get('frac_ge_0p5'), 3)}",
         f"{format_val(held_cap.get('frac_ge_0p5'), 3)}" if s_held else "---"),
        ("Capture $\\ge 0.80$ (Fraction)", 
         f"{format_val(can_cap.get('frac_ge_0p8'), 3)}",
         f"{format_val(held_cap.get('frac_ge_0p8'), 3)}" if s_held else "---"),
        ("Positive Gain Fraction", 
         f"{format_val(can_cap.get('frac_gt_0'), 3)}",
         f"{format_val(held_on.get('frac_positive_gain'), 3)}" if s_held else "---"),
        ("Pearson Correlation $r$", 
         f"{format_val(can_corr.get('pearson'))} {format_ci(can_corr.get('pearson_bootstrap95_ci'))}",
         "---"),
        ("Spearman Correlation $\\rho$", 
         f"{format_val(can_corr.get('spearman'))} {format_ci(can_corr.get('spearman_bootstrap95_ci'))}",
         "---"),
        ("Regression through Origin Slope", 
         f"{format_val(can_reg.get('through_origin_slope'))}",
         "---"),
        ("Ordinary Regression (Slope, Intercept)", 
         f"{format_val(can_reg.get('ordinary_slope'))}, {format_val(can_reg.get('ordinary_intercept'))}",
         "---"),
    ]

    # 1. LaTeX table
    tex_path = out / "table_e6_summary.tex"
    with open(tex_path, "w", encoding="utf-8") as f:
        f.write("% Auto-generated by Phase 1 Grid - ICLR 2027 E6 Summary\n")
        f.write("\\begin{table}[t]\n\\centering\n\\small\n")
        f.write("\\begin{tabular}{lcc}\n\\toprule\n")
        f.write("\\textbf{Metric} & \\textbf{Canonical E6 ($H=180$)} & \\textbf{Held-Out Generalization} \\\\\n\\midrule\n")
        for m, c_val, h_val in metrics:
            f.write(f"{m} & {c_val} & {h_val} \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")
        f.write("\\caption{Summary of Geometry Opportunity and Online Gain Capture across canonical and held-out regular STFT grids.}\n")
        f.write("\\label{tab:e6_summary}\n\\end{table}\n")

    # 2. CSV table
    csv_path = out / "table_e6_summary.csv"
    csv_rows = [
        {"metric": m.replace("$", "").replace("\\textbf", "").replace("\\rm", "").replace("\\Delta_{", "Delta_").replace("}", "").replace("\\ge", ">=").replace("\\rho", "rho"),
         "canonical_e6": c_val,
         "heldout_generalization": h_val}
        for m, c_val, h_val in metrics
    ]
    write_csv(csv_rows, csv_path)

    print(f"[OK] Generated tables:\n     - {tex_path}\n     - {csv_path}")
    return tex_path, csv_path


def main():
    parser = argparse.ArgumentParser(description="Generate E6 summary publication tables")
    parser.add_argument("--e6-summary", default=str(ROOT / "results" / "e6_geometry_opportunity" / "e6_summary.json"))
    parser.add_argument("--heldout-summary", default=str(ROOT / "results" / "e6_geometry_opportunity" / "e6_heldout_summary.json"))
    parser.add_argument("--out", default=str(ROOT / "results" / "e6_geometry_opportunity"))
    args = parser.parse_args()

    heldout_p = args.heldout_summary if Path(args.heldout_summary).exists() else None
    make_tables(args.e6_summary, heldout_p, args.out)


if __name__ == "__main__":
    main()